import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const base = process.env.TEST_BASE_URL ?? 'http://localhost:3107';
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
const snapshot = async () => JSON.parse((await page.evaluate(() => localStorage.getItem('jorata.play.world.v1'))) ?? 'null');
const save = async () => { await page.getByRole('button', { name: 'Save world' }).click(); await page.getByText('Saved on this device', { exact: true }).waitFor(); return snapshot(); };
try {
  await page.goto(`${base}/play`);
  const worldCanvas = page.locator('canvas');
  await worldCanvas.waitFor();
  await page.waitForTimeout(1200);
  const initial = await save(); assert.ok(initial?.version === 1);
  await worldCanvas.focus(); await page.keyboard.down('d'); await page.waitForTimeout(400); await page.keyboard.up('d'); await page.waitForTimeout(300);
  const moved = await save(); assert.ok(moved.player.x > initial.player.x + 25, 'D moves right');
  await worldCanvas.focus(); await page.keyboard.down('Space'); await page.waitForTimeout(140); await page.keyboard.up('Space');
  const jumped = await save(); assert.ok(jumped.player.y < moved.player.y - 15, 'Space jumps');
  await page.waitForTimeout(1100);
  const grounded = await save();
  await worldCanvas.focus(); await page.keyboard.down('Control'); await page.keyboard.press('d'); await page.keyboard.up('Control'); await page.waitForTimeout(250);
  const modified = await save(); assert.ok(Math.abs(modified.player.x - grounded.player.x) < 3, 'Ctrl+D does not move');
  const bounds = await worldCanvas.boundingBox(); assert.ok(bounds);
  const tileX = Math.floor(grounded.player.x / 32), tileY = Math.ceil((grounded.player.y + 30) / 32);
  const cameraX = Math.max(0, Math.min(3200 - bounds.width, grounded.player.x - bounds.width * .45));
  const cameraY = Math.max(0, Math.min(1024 - bounds.height, grounded.player.y - bounds.height * .52));
  const tilePoint = { x: bounds.x + tileX * 32 + 16 - cameraX, y: bounds.y + tileY * 32 + 16 - cameraY };
  await page.getByRole('button', { name: 'Collect', exact: true }).click();
  await page.mouse.click(tilePoint.x, tilePoint.y);
  await page.getByText(/Collected earth\./).waitFor();
  const collected = await save(); assert.equal(collected.collected, 1); assert.equal(collected.inventory.earth, 13);
  await page.getByRole('button', { name: 'Build', exact: true }).click();
  // Place beside the player, above the ground, so gravity cannot move them into the target.
  await page.waitForTimeout(900);
  const beforeBuild = await save();
  const buildX = Math.floor(beforeBuild.player.x / 32) + 2, buildY = Math.floor(beforeBuild.player.y / 32) - 1;
  const buildCameraY = Math.max(0, Math.min(1024 - bounds.height, beforeBuild.player.y - bounds.height * .52));
  await page.mouse.click(bounds.x + buildX * 32 + 16 - cameraX, bounds.y + buildY * 32 + 16 - buildCameraY);
  await page.getByText(/Placed earth\./).waitFor();
  const built = await save(); assert.equal(built.built, 1); assert.equal(built.inventory.earth, 12);
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export world' }).click(); assert.match((await download).suggestedFilename(), /jorata-mosslight.*json/);
  await page.reload(); await worldCanvas.waitFor(); await page.waitForTimeout(300); const restored = await save();
  assert.equal(restored.collected, 1); assert.equal(restored.built, 1); assert.deepEqual(restored.tiles, built.tiles); assert.deepEqual(restored.inventory, built.inventory);
  await page.locator('input[type=file][aria-label="Import world backup"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":900}') });
  await page.getByText(/not a valid JORATA world backup/).waitFor();
  assert.deepEqual((await snapshot()).tiles, built.tiles, 'invalid import preserves world');
  const imported = { ...built, built: 7, savedAt: Date.now() };
  page.once('dialog', dialog => void dialog.accept());
  await page.locator('input[type=file][aria-label="Import world backup"]').setInputFiles({ name: 'world.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(imported)) });
  await page.getByText('Welcome back to your world.').waitFor();
  assert.equal((await save()).built, 7, 'validated backup imports');
  await page.waitForTimeout(900);
  const prePause = await save();
  await worldCanvas.focus(); await page.keyboard.down('Space'); await page.waitForTimeout(120); await page.keyboard.up('Space');
  await page.getByRole('button', { name: 'Quick note', exact: false }).first().click();
  await page.getByRole('dialog', { name: 'Quick note' }).waitFor();
  await page.getByRole('textbox', { name: 'Quick note content' }).fill('A Mosslight idea.');
  await page.waitForTimeout(5200);
  const pausedSnapshot = await snapshot();
  assert.ok(pausedSnapshot.player.y < prePause.player.y - 10, 'world remains paused in midair during quick note');
  await page.getByRole('button', { name: 'Close quick note' }).click();
  await page.waitForTimeout(1200);
  const resumed = await save(); assert.ok(resumed.player.y > pausedSnapshot.player.y + 10, 'physics resumes after quick note');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mp = await mobile.newPage(); await mp.goto(`${base}/play`); await mp.locator('canvas').waitFor();
  const move = mp.getByRole('button', { name: 'Move right', exact: true }); await move.waitFor({ state: 'visible' });
  await mp.getByRole('button', { name: 'Save world' }).click(); await mp.getByText('Saved on this device', { exact: true }).waitFor();
  const mx = await mp.evaluate(() => JSON.parse(localStorage.getItem('jorata.play.world.v1')!).player.x);
  // Real browser pointer capture requires an active pointer.
  const moveBox = await move.boundingBox(); assert.ok(moveBox);
  await mp.mouse.move(moveBox.x + 20, moveBox.y + 20); await mp.mouse.down(); await mp.waitForTimeout(400); await mp.mouse.up();
  await mp.getByRole('button', { name: 'Save world' }).click(); await mp.getByText('Saved on this device', { exact: true }).waitFor();
  const nx = await mp.evaluate(() => JSON.parse(localStorage.getItem('jorata.play.world.v1')!).player.x); assert.ok(nx > mx + 15, 'mobile direction control moves player');
  assert.equal(await mp.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'mobile has no horizontal overflow');
  await mobile.close();
  assert.deepEqual(errors, []);
  console.log('PASS Play browser: movement, jumping, modified keys, collection, building, save/reload, export, invalid/valid import, quick-note pause/resume, mobile controls and layout.');
} finally { await context.close(); await browser.close(); }
