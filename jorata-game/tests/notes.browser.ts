import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const failures: string[] = [];
page.on('pageerror', error => failures.push(error.message));
const base = process.env.TEST_BASE_URL || process.env.BASE_URL || 'http://localhost:3107';
const evidence: string[] = [];
try {
  await page.goto(`${base}/notes`);
  await page.getByRole('button', { name: 'New note' }).click();
  await page.getByLabel('Note title', { exact: true }).fill('Mosslight field journal');
  await page.getByLabel('Note content', { exact: true }).fill('# First expedition\n- Collect stone\n> Keep a little wonder.\n<script>window.injected=true</script>');
  await expect(page.getByRole('status').filter({ hasText: 'Saved to this device' })).toBeVisible();
  await page.getByLabel('New folder name').fill('Expeditions');
  await page.getByRole('button', { name: 'Create folder', exact: true }).click();
  await page.getByLabel('Move note to folder').selectOption('Expeditions');
  await page.getByLabel('Note tags', { exact: true }).fill('world, journal');
  await page.getByRole('button', { name: 'Pin', exact: true }).click();
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'First expedition', exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { injected?: boolean }).injected)).toBeUndefined();
  await expect(page.locator('.jn-markdown')).toContainText('<script>');
  await page.reload();
  await page.getByRole('button', { name: /Mosslight field journal/ }).click();
  await expect(page.getByLabel('Note content', { exact: true })).toHaveValue(/Collect stone/);
  await expect(page.getByLabel('Move note to folder')).toHaveValue('Expeditions');
  await expect(page.getByRole('button', { name: 'Unpin', exact: true })).toBeVisible();
  evidence.push('Create/edit/autosave/reload preserve content, folder, tags and pin; preview renders headings and treats HTML as text.');

  await page.getByLabel('Search notes', { exact: true }).fill('no such thought');
  await expect(page.locator('.jn-empty-copy')).toContainText('No notes match this view.');
  await page.getByLabel('Search notes', { exact: true }).fill('stone');
  await expect(page.locator('.jn-note-row')).toHaveCount(1);
  await page.getByLabel('Search notes', { exact: true }).fill('');
  await page.getByLabel('Filter by tag').selectOption('journal');
  await expect(page.locator('.jn-note-row')).toHaveCount(1);
  await page.getByLabel('Filter by tag').selectOption('');
  await page.getByRole('button', { name: 'New note' }).click();
  await page.getByLabel('Note title', { exact: true }).fill('A second thought');
  await page.getByLabel('Note content', { exact: true }).fill('Remember the mossy ridge.');
  await expect(page.getByRole('status').filter({ hasText: 'Saved to this device' })).toBeVisible();
  await page.getByLabel('Sort notes').selectOption('manual');
  const before = await page.locator('.jn-note-select strong').allTextContents();
  await page.getByRole('button', { name: `Move ${before[1]} up`, exact: true }).click();
  expect(await page.locator('.jn-note-select strong').allTextContents()).toEqual([before[1], before[0]]);
  await page.locator('.jn-note-row').nth(1).dragTo(page.locator('.jn-note-row').first());
  expect(await page.locator('.jn-note-select strong').allTextContents()).toEqual(before);
  await page.locator('.jn-note-row').filter({ hasText: 'A second thought' }).dragTo(page.getByRole('navigation', { name: 'Note folders' }).getByRole('button', { name: /Expeditions/ }));
  await expect(page.getByLabel('Move note to folder')).toHaveValue('Expeditions');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('A second thought.md');
  evidence.push('Search, tag filters, folder move by drag, keyboard reorder and Markdown download work.');
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('button', { name: 'Delete note', exact: true }).click();
  await expect(page.locator('.jn-note-row')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('.jn-note-row')).toHaveCount(1);
  evidence.push('Confirmed note deletion persists after refresh.');
  await mkdir('artifacts/rebuild', { recursive: true });
  await page.getByRole('button', { name: /Mosslight field journal/ }).click();
  await page.screenshot({ path: 'artifacts/rebuild/notes-desktop.png', fullPage: true });

  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel('Note content', { exact: true })).toBeVisible();
  await page.getByLabel('Note content', { exact: true }).fill('Mobile writing survives a refresh.');
  await expect(page.getByRole('status').filter({ hasText: 'Saved to this device' })).toBeVisible();
  await page.getByRole('button', { name: 'Library', exact: false }).click();
  await expect(page.getByLabel('Search notes', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'artifacts/rebuild/notes-mobile-library.png', fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: /Mosslight field journal/ }).click();
  await expect(page.getByLabel('Note content', { exact: true })).toHaveValue('Mobile writing survives a refresh.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/rebuild/notes-mobile.png', fullPage: true });
  evidence.push('390px mobile editing, library navigation, refresh recovery and no horizontal overflow.');

  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/play`);
  await page.getByRole('button', { name: /Quick note/ }).first().click();
  await page.getByLabel('Quick note title', { exact: true }).fill('An idea from the world');
  await page.getByLabel('Quick note content', { exact: true }).fill('A little house on the ridge.');
  await expect(page.getByRole('status').filter({ hasText: 'Saved to Notes on this device' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/rebuild/quick-note-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Return to world' }).click();
  await expect(page.getByRole('dialog', { name: 'Quick note' })).toHaveCount(0);
  await page.goto(`${base}/notes`);
  await page.getByRole('button', { name: /An idea from the world/ }).click();
  await expect(page.getByLabel('Note content', { exact: true })).toHaveValue('A little house on the ridge.');
  evidence.push('Gameplay quick note saves and is recoverable in the Notes library.');
  const touchContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  const touchPage = await touchContext.newPage();
  await touchPage.goto(`${base}/notes`);
  await touchPage.getByRole('button', { name: 'New note' }).tap();
  await touchPage.getByLabel('Note title', { exact: true }).fill('Touch journal');
  await touchPage.getByLabel('Note content', { exact: true }).fill('A note written on a touch device.');
  await expect(touchPage.getByRole('status').filter({ hasText: 'Saved to this device' })).toBeVisible();
  await touchPage.reload();
  await touchPage.getByRole('button', { name: /Touch journal/ }).tap();
  await expect(touchPage.getByLabel('Note content', { exact: true })).toHaveValue('A note written on a touch device.');
  await touchContext.close();
  evidence.push('Mobile touch context creates and recovers notes using tap interactions.');
  const unavailableContext = await browser.newContext();
  await unavailableContext.addInitScript(() => { Object.defineProperty(window, 'indexedDB', { get() { throw new Error('Storage blocked for test'); } }); });
  const unavailablePage = await unavailableContext.newPage();
  await unavailablePage.goto(`${base}/notes`);
  await expect(unavailablePage.getByRole('alert')).toContainText(/notes.*unavailable/i);
  await unavailablePage.getByRole('button', { name: 'New note' }).click();
  await unavailablePage.getByLabel('Note content', { exact: true }).fill('Keep this writing exportable.');
  await expect(unavailablePage.getByRole('status')).toContainText('Not saved');
  const recoveryEvent = unavailablePage.waitForEvent('download');
  await unavailablePage.getByRole('button', { name: 'Export', exact: true }).click();
  expect((await recoveryEvent).suggestedFilename()).toBe('Untitled.md');
  const recoveredPage = await unavailableContext.newPage();
  await recoveredPage.goto(`${base}/notes`);
  await recoveredPage.getByRole('button', { name: /Untitled note/ }).click();
  await expect(recoveredPage.getByLabel('Note content', { exact: true })).toHaveValue('Keep this writing exportable.');
  await unavailableContext.close();
  evidence.push('Blocked IndexedDB surfaces a save failure, keeps Markdown export available, and restores the recovery copy in a new page.');
  expect(failures).toEqual([]);
  await writeFile('artifacts/rebuild/notes-evidence.json', JSON.stringify({ base, evidence, pageErrors: failures }, null, 2));
  console.log(JSON.stringify({ passed: evidence, pageErrors: failures }, null, 2));
} finally { await browser.close(); }
